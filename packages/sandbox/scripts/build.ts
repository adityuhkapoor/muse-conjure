// Bundles the frame runtime (one minified classic script) into src/frame-js.gen.ts, and the host
// API into dist/host.js for pages that load it directly. Prints sizes.
import { gzipSync } from "node:zlib";
import { join } from "node:path";

const root = join(import.meta.dir, "..");

async function bundle(entry: string, format: "iife" | "esm") {
  const r = await Bun.build({ entrypoints: [join(root, entry)], format, minify: true, target: "browser" });
  if (!r.success) throw new AggregateError(r.logs, "build failed");
  return await r.outputs[0]!.text();
}

export async function build() {
  const frame = await bundle("src/frame.ts", "iife");
  await Bun.write(join(root, "src/frame-js.gen.ts"), `// Generated by scripts/build.ts. Do not edit.\nexport const FRAME_JS = ${JSON.stringify(frame)};\n`);
  const host = await bundle("src/index.ts", "esm");
  await Bun.write(join(root, "dist/host.js"), host);
  const runtime = await bundle("../app/src/index.ts", "esm");
  const gz = (s: string) => gzipSync(s, { level: 9 }).length;
  return {
    runtime: { min: runtime.length, gzip: gz(runtime) },
    frame: { min: frame.length, gzip: gz(frame) },
    host: { min: host.length, gzip: gz(host) },
  };
}

if (import.meta.main) {
  const s = await build();
  for (const [k, v] of Object.entries(s)) console.log(`${k.padEnd(8)} ${(v.min / 1024).toFixed(1)} KB min  ${(v.gzip / 1024).toFixed(2)} KB min+gzip`);
}
