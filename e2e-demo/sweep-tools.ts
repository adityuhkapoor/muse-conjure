// `bun e2e-demo/sweep-tools.ts [tool ...] [--history N] [--shell]`: mounts every lab tool in the real
// frame runtime (the checked-in frame-js.gen.ts the shell ships, through @muse/sandbox's pool) and
// lists each one that errors or never reports a size within 8 s. It runs in the installed Google
// Chrome (headless) when there is one: Chrome holds back layout in a cross-origin frame that was
// hidden, which the bundled headless shell does not, and that gap is where tools failed to open
// (every tool, in Chrome 157). `--shell` uses the bundled headless shell instead. Per tool, three opens:
//   example   the example's params, light, 393 px, members without photos
//   empty     the empty skeleton (the composer's shape before a fill), dark, 340 px, photos
//   history   the example after N valid actions from five people (the tool's own `arbitrary`,
//             folded with the server's real seeds), opened fresh on that room, dark, 500 px, photos
// "did not open" is what the shell shows as "This tool didn't open"; "error after open" is an
// error reported after the first size (the tool keeps its last good render). Exits 1 on any failure.

import { chromium } from "playwright";
import { readdirSync, readFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { hostHtml } from "../packages/sandbox/src/harness-build.ts";
import { compileApp } from "../packages/sandbox/src/compile.ts";
import { sourceOf } from "../services/demo/premade.ts";
import { ToolRealm } from "../services/cast/src/realm.ts";

const ROOT = resolve(import.meta.dir, "..");
const LAB = join(ROOT, "library", "lab");
const args = process.argv.slice(2);
const hi = args.indexOf("--history");
const N = hi >= 0 ? Number(args.splice(hi, 2)[1]) : 150;
const si = args.indexOf("--shell");
const useShell = si >= 0 && !!args.splice(si, 1);
const only = new Set(args);
const tools = readdirSync(LAB)
  .filter((id) => !id.startsWith("_") && existsSync(join(LAB, id, "app.tsx")) && existsSync(join(LAB, id, "example.ts")))
  .filter((id) => !only.size || only.has(id))
  .sort();

const photo = (id: string) => {
  const f = join(ROOT, "assets", "img", "avatar", `${id}-112.webp`);
  return existsSync(f) ? `data:image/webp;base64,${readFileSync(f).toString("base64")}` : undefined;
};
const PEOPLE = [
  { id: "dev", name: "Aditya" },
  { id: "jonah", name: "Calvin" },
  { id: "theo", name: "Arun" },
  { id: "maya", name: "Maya" },
  { id: "noa", name: "Noa" },
];
const withFaces = PEOPLE.map((m) => {
  const a = photo(m.id);
  return a ? { ...m, avatar: a } : m;
});

type Open = { sized: number; errors: string[] };
type Row = { id: string; example: string; empty: string; history: string };

const chrome = !useShell && existsSync("/Applications/Google Chrome.app") ? "chrome" : undefined;
const browser = await chromium.launch({ headless: true, ...(chrome ? { channel: chrome } : {}) });
const version = browser.version();
const page = await browser.newPage({ viewport: { width: 1200, height: 1400 } });
await page.setContent(await hostHtml({ width: 680 }));
await page.waitForFunction(() => (window as unknown as { ready?: boolean }).ready === true);
await page.evaluate(() => (window as any).H.makePool(2, { srcdoc: true }));

async function open(code: string, o: { me: string; members: unknown[]; width: number; mode: "light" | "dark"; room?: string }): Promise<Open> {
  return page.evaluate(
    async ([code, o]) => {
      const H = (window as any).H;
      const m = await H.mount(code, { ...o, debug: false });
      // A little longer, for errors right after the first render (clock, members, photos).
      await new Promise((r) => setTimeout(r, 300));
      const s = H.state(m.id);
      H.destroy(m.id);
      return { sized: m.sized, errors: s.errors as string[] };
    },
    [code, o] as const,
  );
}

const verdict = (r: Open) => (r.sized < 0 ? `did not open: ${r.errors[0] ?? "no size in 8 s"}` : r.errors.length ? `error after open: ${r.errors[0]}` : "ok");

/** N actions from five people into `room`, generated by the tool's `arbitrary` on a fold that uses the server's metas. */
async function history(code: string, room: string): Promise<{ acts: number; faults: number }> {
  const realm = new ToolRealm(code, room, { timeoutMs: 500 });
  let f = realm.init();
  const step = async (user: string, action: unknown) => {
    const e = await page.evaluate(
      ([room, user, action]) => {
        const H = (window as any).H;
        H.act(room, user, action);
        return H.log(room).at(-1);
      },
      [room, user, action] as const,
    );
    if (e) f = realm.reduce(f, e.action, { seq: e.seq, user: e.user, time: e.time, seed: e.seed });
  };
  await step("host", { t: "@members", members: PEOPLE });
  let acts = 0;
  let seed = 7;
  for (let i = 0; i < N * 2 && acts < N; i++) {
    const user = PEOPLE[i % PEOPLE.length]!.id;
    const a = realm.arbitrary(f, user, (seed = (seed * 1103515245 + 12345) >>> 0));
    if (a == null) continue;
    await step(user, a);
    acts++;
  }
  const faults = realm.faults;
  realm.close();
  return { acts, faults };
}

const quiet = console.log;
const rows: Row[] = [];
const t0 = performance.now();
let n = 0;
for (const id of tools) {
  n++;
  const row: Row = { id, example: "", empty: "", history: "" };
  let ex: string, empty: string;
  try {
    console.log = () => {};
    const example = ((await import(join(LAB, id, "example.ts"))) as { default: Record<string, unknown> }).default;
    ex = compileApp(await sourceOf({ tool: `lab:${id}`, params: JSON.parse(JSON.stringify(example)) })).code;
    empty = compileApp(await sourceOf({ tool: `lab:${id}`, params: {} })).code;
  } catch (e) {
    row.example = row.empty = row.history = `compile: ${(e as Error).message.slice(0, 120)}`;
    rows.push(row);
    continue;
  } finally {
    console.log = quiet;
  }
  row.example = verdict(await open(ex, { me: "dev", members: PEOPLE, width: 393, mode: "light" }));
  row.empty = verdict(await open(empty, { me: "dev", members: withFaces, width: 340, mode: "dark" }));
  const room = `a:sweep-${id}`;
  try {
    const h = await history(ex, room);
    const r = await open(ex, { me: "dev", members: withFaces, width: 500, mode: "dark", room });
    row.history = verdict(r) + (h.acts < 10 ? ` (only ${h.acts} actions)` : "");
  } catch (e) {
    row.history = `history: ${(e as Error).message.slice(0, 120)}`;
  }
  rows.push(row);
  const bad = [row.example, row.empty, row.history].some((v) => !v.startsWith("ok"));
  if (bad) quiet(`${String(n).padStart(3)} ${id}\n      example: ${row.example}\n      empty:   ${row.empty}\n      history: ${row.history}`);
  else if (n % 20 === 0) quiet(`${String(n).padStart(3)} of ${tools.length} (${Math.round((performance.now() - t0) / 1000)} s)`);
}
await browser.close();

const short = (v: string) => (v.startsWith("ok") ? (v === "ok" ? "ok" : v) : v.split(":")[0]!);
const failed = rows.filter((r) => [r.example, r.empty, r.history].some((v) => !v.startsWith("ok")));
const count = (k: keyof Omit<Row, "id">, p: string) => rows.filter((r) => r[k].startsWith(p)).length;
console.log(`\n${tools.length} tools, ${N} actions of history each, ${version} (${chrome ?? "headless shell"}), ${Math.round((performance.now() - t0) / 1000)} s\n`);
console.log("open      ok   did not open   error after open   other");
for (const k of ["example", "empty", "history"] as const) {
  const ok = count(k, "ok"), dno = count(k, "did not open"), eao = count(k, "error after open");
  console.log(`${k.padEnd(9)} ${String(ok).padStart(3)}   ${String(dno).padStart(12)}   ${String(eao).padStart(16)}   ${String(rows.length - ok - dno - eao).padStart(5)}`);
}
if (failed.length) {
  console.log(`\n${"tool".padEnd(26)} ${"example".padEnd(18)} ${"empty".padEnd(18)} history`);
  for (const r of failed) console.log(`${r.id.padEnd(26)} ${short(r.example).padEnd(18)} ${short(r.empty).padEnd(18)} ${short(r.history)}`);
}
process.exit(failed.length ? 1 : 0);
