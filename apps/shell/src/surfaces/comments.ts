const WHEN: Record<string, number> = { m: 60_000, h: 3_600_000, d: 86_400_000, y: 31_536_000_000 };
/** "40m", "2h", "1d", "1y" as milliseconds. */
export const ageMs = (s: string) => Number(s.slice(0, -1)) * (WHEN[s.slice(-1)] ?? 0);

function flatten(post: string, rows: Raw[]): Seeded[] {
  const out: Seeded[] = [];
  let n = 0;
  for (const [by, text, age, likes = 0, replies = []] of rows) {
    const id = `${post}:${++n}`;
    out.push({ id, by, text, ago: ageMs(age), likes });
    for (const [rby, rtext, rage, rlikes = 0] of replies) out.push({ id: `${post}:${++n}`, by: rby, text: rtext, ago: ageMs(rage), likes: rlikes, parent: id });
  }
  return out;
}

/** Every seeded comment of a post, top level first with its replies right after it. */
export const SEEDED: Record<string, Seeded[]> = Object.fromEntries(Object.entries(T).map(([post, rows]) => [post, flatten(post, rows)]));

export const seededFor = (post: string): Seeded[] => SEEDED[post] ?? [];
